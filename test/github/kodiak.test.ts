import * as TOML from "@iarna/toml";
import { KodiakDependencyVersion, MergeMethod } from "../../src/github";
import { synthSnapshot, TestProject } from "../util";

describe("kodiak", () => {
  test("not generated by default", () => {
    const project = new TestProject();

    const snapshot = synthSnapshot(project);
    expect(project.github?.kodiak).toBeUndefined();
    expect(snapshot[".kodiak.toml"]).toBeUndefined();
  });

  test("enabled with defaults", () => {
    const project = new TestProject({
      githubOptions: {
        mergify: false,
        kodiak: true,
      },
    });

    const snapshot = synthSnapshot(project);
    expect(project.github?.kodiak).toBeDefined();
    expect(snapshot[".kodiak.toml"]).toBeDefined();
    const parsed = TOML.parse(snapshot[".kodiak.toml"]);
    expect(parsed).toEqual({
      version: 1,
    });
  });

  test("custom approve, merge, and update options", () => {
    const project = new TestProject({
      githubOptions: {
        mergify: false,
        kodiak: true,
        kodiakOptions: {
          approve: {
            autoApproveUsernames: ["dependabot[bot]"],
          },
          merge: {
            automergeLabel: "ready",
            requireAutomergeLabel: false,
            method: MergeMethod.SQUASH,
            deleteBranchOnMerge: true,
            doNotMerge: false,
            prioritizeReadyToMerge: true,
            automergeDependencies: {
              versions: [
                KodiakDependencyVersion.MINOR,
                KodiakDependencyVersion.PATCH,
              ],
              usernames: ["dependabot[bot]", "renovate[bot]"],
            },
          },
          update: {
            always: true,
            autoupdateLabel: "autoupdate",
            ignoredUsernames: ["bot-user"],
          },
        },
      },
    });

    const snapshot = synthSnapshot(project);
    const toml = snapshot[".kodiak.toml"];
    expect(toml).toBeDefined();

    const parsed = TOML.parse(toml);
    expect(parsed).toEqual({
      version: 1,
      approve: {
        auto_approve_usernames: ["dependabot[bot]"],
      },
      merge: {
        automerge_label: "ready",
        require_automerge_label: false,
        method: "squash",
        delete_branch_on_merge: true,
        do_not_merge: false,
        prioritize_ready_to_merge: true,
        automerge_dependencies: {
          versions: ["minor", "patch"],
          usernames: ["dependabot[bot]", "renovate[bot]"],
        },
      },
      update: {
        always: true,
        autoupdate_label: "autoupdate",
        ignored_usernames: ["bot-user"],
      },
    });
  });
});
