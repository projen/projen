import { mkdtempSync, readFileSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import * as JSONC from "comment-json";
import type { GitHubApi } from "../../src/github/private/update-github-actions";
import { updateGithubActions } from "../../src/github/private/update-github-actions";

const NOW = new Date("2026-01-01T00:00:00Z").getTime();
const DAY = 24 * 60 * 60 * 1000;

function daysAgo(days: number): string {
  return new Date(NOW - days * DAY).toISOString();
}

interface FakeRepo {
  releases?: any[];
  tagShas?: Record<string, string>;
}

/**
 * A fake GitHub API serving canned releases and tag refs per repository.
 */
function fakeApi(repos: Record<string, FakeRepo>): GitHubApi {
  return async (path: string) => {
    const releases = /^\/repos\/([^/]+\/[^/]+)\/releases/.exec(path);
    if (releases) {
      return repos[releases[1]]?.releases ?? [];
    }
    const tagRef = /^\/repos\/([^/]+\/[^/]+)\/git\/ref\/tags\/(.+)$/.exec(path);
    if (tagRef) {
      const sha = repos[tagRef[1]]?.tagShas?.[tagRef[2]];
      if (!sha) {
        throw new Error(`no tag sha for ${path}`);
      }
      return { object: { type: "commit", sha } };
    }
    throw new Error(`unexpected api call: ${path}`);
  };
}

function writeManifest(manifest: unknown): string {
  const dir = mkdtempSync(join(tmpdir(), "projen-actions-test-"));
  const filePath = join(dir, "github-actions.jsonc");
  writeFileSync(
    filePath,
    `// ~~ Generated by projen. header to preserve\n${JSON.stringify(
      manifest,
      null,
      2,
    )}\n`,
  );
  return filePath;
}

function readManifest(filePath: string): any {
  return JSONC.parse(readFileSync(filePath, "utf-8"), undefined, true);
}

describe("updateGithubActions", () => {
  test("pins an immutable release tag", async () => {
    const filePath = writeManifest({
      actions: {
        "actions/checkout": { major: "v7", majorLocked: true },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [
            {
              tag_name: "v7.1.0",
              immutable: true,
              published_at: daysAgo(10),
            },
            { tag_name: "v7.0.0", immutable: true, published_at: daysAgo(40) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/checkout"]).toEqual({
      major: "v7",
      majorLocked: true,
      pin: "v7.1.0",
      isImmutable: true,
    });
  });

  test("resolves mutable release tags to commit SHAs", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [{ tag_name: "v7.0.1", published_at: daysAgo(10) }],
          tagShas: { "v7.0.1": "cafebabe" },
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/checkout"]).toEqual({
      major: "v7",
      majorLocked: true,
      pin: "cafebabe",
      version: "v7.0.1",
    });
  });

  test("pins plain tags with --mutable-pins", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      mutablePins: true,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [{ tag_name: "v7.0.1", published_at: daysAgo(10) }],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/checkout"]).toEqual({
      major: "v7",
      majorLocked: true,
      pin: "v7.0.1",
    });
  });

  test("ignores releases within the cooldown", async () => {
    const filePath = writeManifest({
      actions: {
        "actions/checkout": {
          major: "v7",
          majorLocked: true,
          pin: "v7.0.0",
          isImmutable: true,
        },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      cooldownDays: 7,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [
            { tag_name: "v7.1.0", immutable: true, published_at: daysAgo(2) },
            { tag_name: "v7.0.0", immutable: true, published_at: daysAgo(40) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/checkout"].pin).toBe(
      "v7.0.0",
    );
  });

  test("never upgrades locked majors, but reports them", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });
    const logs: string[] = [];

    await updateGithubActions({
      filePath,
      now: NOW,
      reportMajorVersions: true,
      log: (m) => logs.push(m),
      api: fakeApi({
        "actions/checkout": {
          releases: [
            { tag_name: "v8.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v7.9.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/checkout"]).toEqual({
      major: "v7",
      majorLocked: true,
      pin: "v7.9.0",
      isImmutable: true,
    });
    expect(logs).toContain("new major available: actions/checkout v8");
  });

  test("does not report new majors by default", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });
    const logs: string[] = [];

    await updateGithubActions({
      filePath,
      now: NOW,
      log: (m) => logs.push(m),
      api: fakeApi({
        "actions/checkout": {
          releases: [
            { tag_name: "v8.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v7.9.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(logs).not.toContain("new major available: actions/checkout v8");
  });

  test("adopts the latest major for actions without a declared major", async () => {
    const filePath = writeManifest({
      actions: { "actions/setup-node": {} },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "actions/setup-node": {
          releases: [
            { tag_name: "v5.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v4.0.0", immutable: true, published_at: daysAgo(90) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/setup-node"]).toEqual({
      major: "v5",
      pin: "v5.0.0",
      isImmutable: true,
    });
  });

  test("upgrades unlocked majors when enabled", async () => {
    const filePath = writeManifest({
      actions: {
        "actions/setup-node": { major: "v4", pin: "v4.0.0", isImmutable: true },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      upgradeMajorVersions: true,
      log: () => {},
      api: fakeApi({
        "actions/setup-node": {
          releases: [
            { tag_name: "v5.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v4.0.0", immutable: true, published_at: daysAgo(90) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/setup-node"]).toEqual({
      major: "v5",
      pin: "v5.0.0",
      isImmutable: true,
    });
  });

  test("keeps unlocked majors without upgrade options", async () => {
    const filePath = writeManifest({
      actions: {
        "actions/setup-node": { major: "v4", pin: "v4.0.0", isImmutable: true },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "actions/setup-node": {
          releases: [
            { tag_name: "v5.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v4.1.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(readManifest(filePath).actions["actions/setup-node"]).toEqual({
      major: "v4",
      pin: "v4.1.0",
      isImmutable: true,
    });
  });

  test("--upgrade-major upgrades a single action", async () => {
    const filePath = writeManifest({
      actions: {
        "actions/setup-node": { major: "v4", pin: "v4.0.0", isImmutable: true },
        "actions/setup-go": { major: "v5", pin: "v5.0.0", isImmutable: true },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      upgradeMajor: ["actions/setup-node"],
      log: () => {},
      api: fakeApi({
        "actions/setup-node": {
          releases: [
            { tag_name: "v5.0.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
        "actions/setup-go": {
          releases: [
            { tag_name: "v6.0.0", immutable: true, published_at: daysAgo(30) },
            { tag_name: "v5.0.0", immutable: true, published_at: daysAgo(90) },
          ],
        },
      }),
    });

    const manifest = readManifest(filePath);
    expect(manifest.actions["actions/setup-node"].major).toBe("v5");
    expect(manifest.actions["actions/setup-go"].major).toBe("v5");
  });

  test("--upgrade-major on a locked action fails with guidance", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });

    await expect(
      updateGithubActions({
        filePath,
        now: NOW,
        upgradeMajor: ["actions/checkout"],
        log: () => {},
        api: fakeApi({}),
      }),
    ).rejects.toThrow(/locked to "v7" by your projenrc/);
  });

  test("--upgrade-major on an unknown action fails", async () => {
    const filePath = writeManifest({ actions: {} });

    await expect(
      updateGithubActions({
        filePath,
        now: NOW,
        upgradeMajor: ["actions/unknown"],
        log: () => {},
        api: fakeApi({}),
      }),
    ).rejects.toThrow(/Unknown action "actions\/unknown"/);
  });

  test("dry-run does not write the manifest", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });
    const before = readFileSync(filePath, "utf-8");

    await updateGithubActions({
      filePath,
      now: NOW,
      dryRun: true,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [
            { tag_name: "v7.1.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(readFileSync(filePath, "utf-8")).toBe(before);
  });

  test("preserves comments (including the projen marker) when writing", async () => {
    const filePath = writeManifest({
      actions: { "actions/checkout": { major: "v7", majorLocked: true } },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "actions/checkout": {
          releases: [
            { tag_name: "v7.1.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(readFileSync(filePath, "utf-8")).toContain(
      "// ~~ Generated by projen. header to preserve",
    );
  });

  test("uses the repository of actions in subdirectories", async () => {
    const filePath = writeManifest({
      actions: {
        "github/codeql-action/init": { major: "v3", majorLocked: true },
      },
    });

    await updateGithubActions({
      filePath,
      now: NOW,
      log: () => {},
      api: fakeApi({
        "github/codeql-action": {
          releases: [
            { tag_name: "v3.2.0", immutable: true, published_at: daysAgo(30) },
          ],
        },
      }),
    });

    expect(
      readManifest(filePath).actions["github/codeql-action/init"].pin,
    ).toBe("v3.2.0");
  });
});
